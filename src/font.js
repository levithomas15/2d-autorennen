export function textWidth(str, scale = 1) {
  return str.length * 4 * scale - scale;
}

export function drawText(g, str, x, y, scale = 1, color = '#fff') {
  g.fillStyle = color;
  const s = String(str).toUpperCase();
  let cx = Math.round(x);
  for (const ch of s) {
    const bits = G[ch];
    if (bits) {
      for (let r = 0; r < 5; r++) {
        for (let c = 0; c < 3; c++) {
          if (bits[r * 3 + c] === '1') {
            g.fillRect(cx + c * scale, Math.round(y) + r * scale, scale, scale);
          }
        }
      }
    }
    cx += 4 * scale;
  }
}

export function drawTextShadow(g, str, x, y, scale = 1, color = '#fff', shadow = 'rgba(0,0,0,.65)') {
  drawText(g, str, x + scale, y + scale, scale, shadow);
  drawText(g, str, x, y, scale, color);
}
